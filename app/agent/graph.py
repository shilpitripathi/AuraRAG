def initial_router(state: AgentState):
    """
    Route from decision node to the appropriate starting node.
    """
    route = state.get("route", "rag")
    if route == "clarification":
        return "end"
    elif route == "file_action":
        return "file_action"
    elif route == "mcp":
        return "mcp"
    elif route == "combined":
        return "combined"
    return "rag"


