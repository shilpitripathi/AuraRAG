# FILE ACTION NODE (Controlled Local File Agent)
# ============================================================

async def file_action_node(state: AgentState):
    """
    Handle local file discovery, selection, and ingestion into AuraRAG.
    Enforces strict path safety and asks for user choice if multiple files match.
    In cloud deployments, directs the user to use the browser upload tool.
    """
    # 0. Distinguish between local development and cloud deployment
    enable_local = os.getenv("ENABLE_LOCAL_FILE_ACCESS", "true").lower() in ("true", "1", "yes")
    deploy_env = os.getenv("DEPLOYMENT_ENV", "").lower()

    if not enable_local or deploy_env in ("production", "prod", "cloud"):
        return {
            "context": "",
            "answer": "In cloud deployment, AuraRAG cannot access your personal computer's local folders. Please use the document upload section in your browser to add documents directly.",
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": None
        }

    query = state["query"].strip()
    query_lower = query.lower()

    # 1. Identify target directory if specified in query
    target_dir = None
    if "download" in query_lower:
        target_dir = "downloads"
    elif "document" in query_lower and (
        "in document" in query_lower or "from document" in query_lower
        or "in my document" in query_lower or "from my document" in query_lower
        or "in documents" in query_lower or "from documents" in query_lower
    ):
        target_dir = "documents"
    elif "desktop" in query_lower:
        target_dir = "desktop"

    # 2. Extract file search description / target name from query
    target_name = re.sub(
        r'^(can you please|could you please|please|can you|could you)\s+',
        '',
        query,
        flags=re.IGNORECASE
    )
    target_name = re.sub(
        r'^(upload my|upload the|upload a|upload an|upload|find my|find the|find and upload|find|ingest|load)\s+',
        '',
        target_name,
        flags=re.IGNORECASE
    )
    target_name = re.sub(
        r'\s+(from|in|to)\s+(downloads|my downloads|documents|my documents|desktop|my desktop|folder|directory).*$',
        '',
        target_name,
        flags=re.IGNORECASE
    ).strip(" .,!?:;'\"")

    # Normalize spoken filename artifacts (e.g. "machine underscore learning" -> "machine_learning")
    target_name = re.sub(r'\bunderscore\b', '_', target_name, flags=re.IGNORECASE)
    target_name = re.sub(r'\bdash\b|\bhyphen\b', '-', target_name, flags=re.IGNORECASE)
    target_name = re.sub(r'\s*_\s*', '_', target_name)
    target_name = re.sub(r'\s*-\s*', '-', target_name)
    target_name = re.sub(r'\bdot\s*pdf\b', '.pdf', target_name, flags=re.IGNORECASE)
    target_name = re.sub(r'\bdot\s*docx\b', '.docx', target_name, flags=re.IGNORECASE)
    target_name = re.sub(r'\bdot\s*txt\b', '.txt', target_name, flags=re.IGNORECASE)
    target_name = re.sub(r'\s*\.\s*(pdf|docx|txt)\b', r'.\1', target_name, flags=re.IGNORECASE)
    target_name = target_name.strip(" .,!?:;'\"")

    if not target_name:
        target_name = query

    # 3. Path safety check if user supplied an absolute/relative path
    if "/" in target_name or "\\" in target_name or ":" in target_name:
        try:
            raw_path = Path(target_name).resolve()
            if not is_path_allowed(raw_path):
                return {
                    "context": "",
                    "answer": "Access denied: I can only access files in your Downloads, Documents, and Desktop folders.",
                    "route": "file_action",
                    "is_clarification": False,
                    "uploaded_document": None
                }
        except Exception:
            return {
                "context": "",
                "answer": "Access denied: Invalid file path specified.",
                "route": "file_action",
                "is_clarification": False,
                "uploaded_document": None
            }

    # 4. Search allowed directories
    try:
        candidates = find_file(target_name, directory=target_dir)
    except PermissionError:
        return {
            "context": "",
            "answer": "Access denied: That directory is outside your approved user folders.",
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": None
        }

    # Case A: No matching files found
    if not candidates:
        dir_text = f"your {target_dir.capitalize()} folder" if target_dir else "your Downloads, Documents, and Desktop folders"
        return {
            "context": "",
            "answer": f"I couldn't find any documents matching '{target_name}' in {dir_text}. Please make sure the file exists and is a PDF, DOCX, or TXT file.",
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": None
        }

    # Case B: Multiple candidates found -> Ask the user to choose (NEVER randomly select one)
    if len(candidates) > 1:
        # Check if the user specified an exact filename match (handling number-words like 'one' -> '1')
        target_norm = normalize_text_numbers(target_name.lower())
        exact_matches = [
            c for c in candidates
            if target_name.lower() == c["filename"].lower()
            or target_name.lower() == Path(c["filename"]).stem.lower()
            or target_norm == normalize_text_numbers(c["filename"].lower())
            or target_norm == normalize_text_numbers(Path(c["filename"]).stem.lower())
        ]
        if len(exact_matches) == 1:
            chosen = exact_matches[0]
        else:
            cand_names = [f"'{c['filename']}'" for c in candidates[:4]]
            return {
                "context": "",
                "answer": f"I found {len(candidates)} matching files: {', '.join(cand_names)}. Which one should I upload?",
                "route": "file_action",
                "is_clarification": False,
                "uploaded_document": None
            }
    else:
        chosen = candidates[0]

    # Case C: Exactly one candidate -> Safely select and upload to RAG
    try:
        file_info = select_file(chosen["path"], candidates=candidates)
        upload_result = upload_to_rag(file_info["path"])

        new_doc_name = upload_result["filename"]
        chunk_count = upload_result["number_of_chunks"]

        confirmation = (
            f"Done! I've uploaded '{new_doc_name}' ({chunk_count} chunks) into AuraRAG. "
            f"It is now your active document. What would you like to know about it?"
        )

        return {
            "context": f"File ingested: {new_doc_name} ({chunk_count} chunks)",
            "answer": confirmation,
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": new_doc_name,
            "source": new_doc_name
        }
    except PermissionError:
        return {
            "context": "",
            "answer": "Access denied: I can only access files in your Downloads, Documents, and Desktop folders.",
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": None
        }
    except Exception as e:
        return {
            "context": "",
            "answer": f"I encountered an error uploading '{chosen.get('filename', 'the file')}': {str(e)}",
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": None
        }


