# ============================================================
# AGENT STATE
# ============================================================

class AgentState(TypedDict):
    # User's question or command
    query: str

    # Information retrieved from RAG, MCP, or file actions
    context: str

    # Final answer generated by Groq or file action confirmation
    answer: str

    # Decision / route executed (rag, mcp, combined, clarification, mcp_fallback, file_action)
    route: str

    # Currently selected/uploaded document
    source: str | None

    # Flag indicating whether this is a clarification response (no TTS audio)
    is_clarification: bool | None

    # Newly uploaded document name from a file action (updates activeDocument in UI)
    uploaded_document: str | None


