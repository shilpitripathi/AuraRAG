graph_builder.add_node("decision", decision_node)
graph_builder.add_node("rag", rag_node)
graph_builder.add_node("mcp", mcp_node)
graph_builder.add_node("mcp_fallback", mcp_fallback_node)
graph_builder.add_node("combined", combined_node)
graph_builder.add_node("file_action", file_action_node)

# START -> decision
graph_builder.add_edge(START, "decision")

# decision -> (clarification -> END | file_action | mcp | combined | rag)
graph_builder.add_conditional_edges(
    "decision",
    initial_router,
    {
        "end": END,
        "file_action": "file_action",
        "mcp": "mcp",
        "combined": "combined",
        "rag": "rag"
    }
)

# rag -> (mcp_fallback | end)
graph_builder.add_conditional_edges(
    "rag",
    rag_router,
    {
        "mcp_fallback": "mcp_fallback",
        "end": END
    }
)

# Terminal edges
graph_builder.add_edge("mcp", END)
graph_builder.add_edge("mcp_fallback", END)
graph_builder.add_edge("combined", END)
graph_builder.add_edge("file_action", END)

