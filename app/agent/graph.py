# NATURAL LANGUAGE SEARCH PARSER
# ============================================================

def parse_search_request(query: str) -> dict | None:
    """
    Extract search objective and focused queries from a natural language query.
    Returns None if there is no actual topic to search for (e.g. 'Search the web').
    """
    clean_q = query.strip()
    clean_q = re.sub(r'^[“"\'`]+|[”"\'`?.!]+$', '', clean_q).strip()

    # Normalize STT phonetic variations for key technologies
    clean_q = re.sub(r'\b(lengraf|lengraff|landgraph|lan\s*graph)\b', 'LangGraph', clean_q, flags=re.IGNORECASE)

    # Remove polite openers
    clean_q = re.sub(
        r'^(could you please|can you please|would you please|please|kindly|can you|could you)\s+',
        '',
        clean_q,
        flags=re.IGNORECASE
    ).strip()

    prefixes = [
        r"search the web for\b",
        r"search the web about\b",
        r"search the web on\b",
        r"search online for\b",
        r"search online about\b",
        r"search online on\b",
        r"search the internet for\b",
        r"search the internet about\b",
        r"web search for\b",
        r"web search about\b",
        r"google for\b",
        r"google about\b",
        r"look up online for\b",
        r"look up online about\b",
        r"look up\b",
        r"find current information about\b",
        r"find current information on\b",
        r"find information about\b",
        r"find information on\b",
        r"search for\b",
        r"search about\b",
        r"search the web\b",
        r"search online\b",
        r"search the internet\b",
        r"web search\b",
        r"google\b",
        r"search\b",
    ]

    matched_prefix = False
    topic = clean_q

    for p in prefixes:
        match = re.match(r"^" + p, topic, flags=re.IGNORECASE)
        if match:
            matched_prefix = True
            topic = topic[match.end():].strip(" :,-?!.")
            break

    if matched_prefix and not topic:
        return None

    if not re.search(r'\w', topic):
        return None

    topic_clean = re.sub(
        r'^(what is the|what is|what are the|what are|what was the|what was|what were|what happened in|what happened|what\'s the|what\'s|tell me about the|tell me about|give me the|give me)\s+',
        '',
        topic,
        flags=re.IGNORECASE
    ).strip()

    if not topic_clean:
        topic_clean = topic

    topic_title = topic_clean[0].upper() + topic_clean[1:] if topic_clean else ""
    if topic_clean.lower().startswith(("find", "get", "search")):
        objective = topic_title
    elif topic_clean.lower().startswith("the "):
        objective = f"Find {topic_clean}"
    elif topic_clean.lower().startswith(("latest", "current", "recent")):
        objective = f"Find the {topic_clean}"
    else:
        objective = f"Find information about {topic_clean}"

    core_term = re.sub(r'^(the|a|an)\s+', '', topic_clean, flags=re.IGNORECASE).strip()
    search_queries = []
    core_lower = core_term.lower()

    if "developments" in core_lower or "updates" in core_lower:
        sub_match = re.search(r'\b(?:in|about|for|of)\s+([A-Za-z0-9_. -]+)$', core_term, flags=re.IGNORECASE)
        if sub_match:
            subject = sub_match.group(1).strip()
        else:
            subject = re.sub(r'\b(latest|recent|current|developments|updates|new)\b', '', core_term, flags=re.IGNORECASE).strip()
            subject = re.sub(r'\s+', ' ', subject).strip()

        if subject:
            search_queries.append(f"latest {subject} developments")
            search_queries.append(f"{subject} recent updates")
            search_queries.append(f"{subject} new features")
        else:
            search_queries.append(core_term)
            search_queries.append(f"{core_term} updates")
    elif "news" in core_lower:
        entity = re.sub(r'\b(latest|recent|current|today\'s|today|news)\b', '', core_term, flags=re.IGNORECASE).strip()
        entity = re.sub(r'\s+', ' ', entity).strip()
        if entity:
            search_queries.append(f"latest {entity} news")
            search_queries.append(f"{entity} news today")
            search_queries.append(f"recent {entity} updates")
        else:
            search_queries.append(core_term)
            search_queries.append(f"{core_term} today")
    else:
        search_queries.append(core_term)
        search_queries.append(f"{core_term} latest updates")
        search_queries.append(f"{core_term} recent developments")

    final_queries = []
    for q in search_queries:
        q_clean = re.sub(r'\s+', ' ', q).strip()
        if q_clean and q_clean not in final_queries:
            final_queries.append(q_clean)

    return {
        "objective": objective,
        "search_queries": final_queries[:3]
    }


# ============================================================
# DECISION NODE
# ============================================================

def decision_node(state: AgentState):
    """
    Determine where the question should initially be routed:
    1. Empty search -> clarification (asks for topic, suppresses TTS audio)
    2. File action -> file_action (find, select, upload local document to RAG)
    3. Comparison/combined -> combined (RAG + MCP)
    4. Explicit web search -> mcp
    5. Default -> rag (inspects active document, answers or falls back to MCP if needed)
    """
    query = state["query"].strip()

    # 1. Empty search intent (e.g. clicked "Search the web" button or said "Search the web")
    if is_empty_search_intent(query):
        return {
            "route": "clarification",
            "context": "",
            "answer": "Sure — what would you like me to search for?",
            "is_clarification": True,
            "uploaded_document": None
        }

    # 2. Local File Action (Upload, Find, Ingest local files)
    if is_file_action_query(query):
        return {
            "route": "file_action",
            "is_clarification": False,
            "uploaded_document": None
        }

    # 3. Combined comparison query (PDF + Online)
    if is_combined_query(query):
        return {
            "route": "combined",
            "is_clarification": False,
            "uploaded_document": None
        }

    # 4. Explicit web search with a topic
    if is_explicit_web_search(query):
        return {
            "route": "mcp",
            "is_clarification": False,
            "uploaded_document": None
        }

    # 5. Default to RAG:
    return {
        "route": "rag",
        "is_clarification": False,
        "uploaded_document": None
    }


