# QUERY INTENT CLASSIFIERS
# ============================================================

def is_empty_search_intent(query: str) -> bool:
    """
    Check if the user provided an empty search request (e.g. clicked 'Search the web')
    without specifying any search topic.
    """
    clean_q = query.strip()
    clean_q = re.sub(r'^[“"\'`]+|[”"\'`?.!]+$', '', clean_q).strip().lower()
    empty_searches = {
        "search the web",
        "search online",
        "search the internet",
        "search internet",
        "web search",
        "google",
        "search",
        "look up online",
        "look up",
        "find online",
        "browse the web",
        "browse online",
    }
    return clean_q in empty_searches


def is_file_action_query(query: str) -> bool:
    """
    Detect whether the user is instructing AuraRAG to perform a local file action:
    finding, selecting, or uploading a file into RAG.
    Guards against questions about document contents (which belong to RAG).
    """
    q = query.lower().strip()

    # Guard: Questions about document contents are RAG or Combined, NOT file actions
    question_starters = [
        "what does", "what is in", "what are", "explain", "summarize",
        "tell me about", "does my", "how does", "compare", "what was",
        "where in", "is there", "can you tell me what"
    ]
    if any(q.startswith(starter) for starter in question_starters):
        # Only treat as file action if explicit upload command is embedded
        if not re.search(r'\b(upload|find\s+and\s+upload|ingest|load)\b', q):
            return False

    file_action_patterns = [
        r"\bupload\s+(my|the|a|an)?\s*[a-zA-Z0-9_\-\.\s]+\b(from|in|to)\b",
        r"\bupload\s+[a-zA-Z0-9_\-]+\.(pdf|docx|txt)\b",
        r"\bupload\s+(my|the|a|an)?\s*[a-zA-Z0-9_\-\s]+\b(pdf|docx|document|file|notes|resume)\b",
        r"\bfind\s+(my|the|a|an)?\s*[a-zA-Z0-9_\-\s]+and\s+upload\b",
        r"\bfind\s+and\s+upload\b",
        r"\bingest\s+(my|the|a|an)?\s*[a-zA-Z0-9_\-\.\s]+\b",
        r"\bload\s+[a-zA-Z0-9_\-\.\s]+\s+(from|into)\b",
        r"^upload\b",
    ]
    return any(re.search(pat, q) for pat in file_action_patterns)


def is_combined_query(query: str) -> bool:
    """
    Check if the user is asking to compare or combine the uploaded document
    with external online / latest developments.
    """
    q = query.lower()

    has_compare = any(kw in q for kw in [
        "compare", "comparison", "difference between", "how does", "versus", "vs", "both"
    ])
    has_doc = any(kw in q for kw in [
        "pdf", "document", "file", "resume", "cv", "paper", "uploaded", "my project"
    ])
    has_online = any(kw in q for kw in [
        "online", "web", "internet", "latest", "recent", "current", "developments", "trends", "news", "google"
    ])

    if has_compare and has_doc and has_online:
        return True

    explicit_combined = [
        "compare with online",
        "compare to online",
        "compare with the web",
        "compare to the web",
        "both my document and",
        "both the document and",
        "both pdf and",
        "both the pdf and",
        "document and online",
        "pdf and online",
        "pdf and the web",
        "compare what is in my pdf with latest information online",
        "compare what is in my pdf with latest",
    ]
    return any(kw in q for kw in explicit_combined)


def is_explicit_web_search(query: str) -> bool:
    """
    Check if the query explicitly commands a web search for a specific topic.
    """
    q = query.lower().strip()
    if is_empty_search_intent(q):
        return False

    explicit_prefixes = [
        r"^search the web for\b",
        r"^search the web about\b",
        r"^search the web on\b",
        r"^search online for\b",
        r"^search online about\b",
        r"^search online on\b",
        r"^search the internet for\b",
        r"^search the internet about\b",
        r"^web search for\b",
        r"^web search about\b",
        r"^google for\b",
        r"^google about\b",
        r"^google\b",
        r"^look up online for\b",
        r"^look up online about\b",
        r"^search for\b",
    ]
    return any(re.search(pat, q) for pat in explicit_prefixes)


