# MCP NODE (Direct MCP search)
# ============================================================

async def mcp_node(state: AgentState):
    """
    Handle explicit web search requests via the external MCP server.
    """
    query = state["query"].strip()

    search_req = parse_search_request(query)
    if not search_req:
        return {
            "context": "",
            "answer": "Sure — what would you like me to search for?",
            "route": "clarification",
            "is_clarification": True,
            "uploaded_document": None
        }

    try:
        result = await call_mcp_tool(
            "web_search",
            {
                "objective": search_req["objective"],
                "search_queries": search_req["search_queries"]
            }
        )
    except Exception as e:
        return {
            "context": "",
            "answer": f"I was unable to search the web because the external MCP service encountered an error: {str(e)}",
            "route": "mcp",
            "is_clarification": False,
            "uploaded_document": None
        }

    context = format_mcp_result(result)
    if not context.strip():
        return {
            "context": "",
            "answer": "I searched the web using the external MCP service, but no relevant results were found.",
            "route": "mcp",
            "is_clarification": False,
            "uploaded_document": None
        }

    MAX_CONTEXT_CHARS = 6000
    if len(context) > MAX_CONTEXT_CHARS:
        context = context[:MAX_CONTEXT_CHARS]

    prompt = f"""You are AuraRAG, a voice-first AI assistant.

Answer the user's question using the external search information provided below.

Rules:
- Give a direct, factual, and informative answer based on the search results.
- Use simple, natural language suitable for voice reading.
- Keep the answer concise and well-structured.
- Do not reproduce raw URLs or JSON formatting.
- Do not mention MCP, internal tools, or the retrieval process.

External search results:
{context}

User question:
{query}
"""
    response = await llm.ainvoke(prompt)

    return {
        "context": context,
        "answer": response.content.strip(),
        "route": "mcp",
        "is_clarification": False,
        "uploaded_document": None
    }


