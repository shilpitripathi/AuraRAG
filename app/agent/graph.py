# MCP FALLBACK NODE (RAG -> MCP fallback)
# ============================================================

async def mcp_fallback_node(state: AgentState):
    """
    Executed when the uploaded document does not contain the required current/external information.
    Performs external MCP web search to find current information and synthesizes the answer.
    """
    query = state["query"].strip()

    search_req = parse_search_request(query)
    if not search_req:
        clean_topic = re.sub(
            r'^(what is the|what are the|what is|what are|tell me about)\s+',
            '',
            query,
            flags=re.IGNORECASE
        ).strip(" ?.")
        search_req = {
            "objective": f"Find information about {clean_topic}",
            "search_queries": [clean_topic, f"{clean_topic} latest developments"]
        }

    try:
        result = await call_mcp_tool(
            "web_search",
            {
                "objective": search_req["objective"],
                "search_queries": search_req["search_queries"]
            }
        )
    except Exception as e:
        return {
            "context": "",
            "answer": f"The document did not contain that information, and searching online failed: {str(e)}",
            "route": "mcp_fallback",
            "is_clarification": False,
            "uploaded_document": None
        }

    context = format_mcp_result(result)
    if not context.strip():
        return {
            "context": "",
            "answer": "The document did not contain that information, and no relevant online search results were found.",
            "route": "mcp_fallback",
            "is_clarification": False,
            "uploaded_document": None
        }

    MAX_CONTEXT_CHARS = 6000
    if len(context) > MAX_CONTEXT_CHARS:
        context = context[:MAX_CONTEXT_CHARS]

    prompt = f"""You are AuraRAG, a voice-first AI assistant.

The user asked a question that was not answered by their uploaded document and requires current external information.
Answer the user's question accurately, naturally, and concisely based on the online search results below.

Rules:
- Give a direct, factual, informative answer.
- Suitable for voice reading.
- Do not mention MCP or internal tools.

Online search results:
{context}

User question:
{query}
"""
    response = await llm.ainvoke(prompt)

    return {
        "context": context,
        "answer": response.content.strip(),
        "route": "mcp_fallback",
        "is_clarification": False,
        "uploaded_document": None
    }


# ============================================================
# COMBINED NODE (RAG + MCP)
# ============================================================

async def combined_node(state: AgentState):
    """
    Executed when the user asks to compare or combine the uploaded document with online information.
    Retrieves document chunks from ChromaDB AND performs external MCP web search,
    then synthesizes a cohesive comparative answer.
    """
    query = state["query"].strip()
    source = state.get("source")
    if source:
        source = source.strip()

    # 1. Retrieve document context
    doc_chunks = []
    if source:
        doc_chunks = get_document_chunks(source=source, limit=4)
        if not doc_chunks:
            res = search_chunks(query, source=source, n_results=4)
            doc_chunks = res["documents"][0] if res.get("documents") else []

    doc_context = "\n\n".join(doc_chunks) if doc_chunks else "No specific document context available."

    # 2. Formulate online search queries
    query_gen_prompt = f"""Given the comparison question: "{query}" and active document: "{source or 'document'}",
extract 2 concise keyword web search queries (comma-separated) to find current online information to compare with.
Search queries:"""
    try:
        q_resp = await llm.ainvoke(query_gen_prompt)
        raw_queries = [q.strip() for q in q_resp.content.split(",") if q.strip()]
        search_queries = raw_queries[:2] if raw_queries else [query]
    except Exception:
        search_queries = ["latest AI Agent developments LangChain LangGraph", "AI Engineering current trends"]

    objective = f"Find online information to compare with {source or 'document'}"

    # 3. Call MCP web search
    mcp_context = ""
    try:
        result = await call_mcp_tool(
            "web_search",
            {
                "objective": objective,
                "search_queries": search_queries
            }
        )
        mcp_context = format_mcp_result(result)
    except Exception as e:
        mcp_context = f"Online search could not be completed: {e}"

    MAX_CONTEXT_CHARS = 4000
    if len(mcp_context) > MAX_CONTEXT_CHARS:
        mcp_context = mcp_context[:MAX_CONTEXT_CHARS]

    # 4. Synthesize comparative answer
    prompt = f"""You are AuraRAG, a voice-first AI assistant.

The user is asking to compare or combine information from their uploaded document with the latest online information.

Synthesize a comprehensive, clear, and direct comparative answer that:
1. Highlights what the uploaded document contains or approaches.
2. Explains the current state-of-the-art / developments found online.
3. Compares the two perspectives clearly.

Suitable for voice reading. Avoid markdown tables.

Document Context ({source or 'Active Document'}):
{doc_context}

Online Search Context:
{mcp_context}

User Question:
{query}
"""
    response = await llm.ainvoke(prompt)
    answer = response.content.strip()

    combined_context = f"=== Document Context ({source}) ===\n{doc_context}\n\n=== Online Context ===\n{mcp_context}"

    return {
        "context": combined_context,
        "answer": answer,
        "route": "combined",
        "is_clarification": False,
        "uploaded_document": None
    }


